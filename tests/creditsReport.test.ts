function file(path: string, size = 1000) {
  return { path, size };
}

describe("reading a licence", () => {
  it("reads CC0, with or without a version", () => {
    expect(readLicence("CC0")).toEqual({ status: "ok", label: "CC0" });
    expect(readLicence("CC0 1.0 (License.txt in both packs)").label).toBe("CC0");
  });

  it("reads CC BY only when the line names an author with the word by", () => {
    expect(readLicence('"Ogre" (https://example.com) by Sam Pie is licensed under CC BY 4.0')).toEqual({
      status: "ok",
      label: "CC BY 4.0, by Sam Pie",
    });
    expect(readLicence("Ogre, CC BY 4.0")).toEqual({ status: "no-author", label: "CC BY 4.0" });
    expect(readLicence("CC-BY", "Ogre by Sam Pie | CC-BY").label).toBe("CC BY, by Sam Pie");
  });

  it("reads work made by the team", () => {
    expect(readLicence("was generated by the team with ElevenLabs.")).toEqual({
      status: "ok",
      label: "generated by the team with ElevenLabs",
    });
    expect(readLicence("made by the team").status).toBe("ok");
  });

  it("does not take a tool's terms of service for a licence", () => {
    expect(readLicence("ElevenLabs Terms of Service and Music Terms, see below").status).toBe("missing");
    expect(readLicence("`public/audio/x.mp3` breaks the ElevenLabs Terms of Service.").status).toBe("missing");
    const head = ["| Clip | File | Source | Licence |", "|---|---|---|---|"];
    const terms = "| Battle music | `public/audio/music/fight.mp3` | ElevenLabs music | ElevenLabs Terms of Service |";
    const ours = "| Win sting | `public/audio/music/win.mp3` | ElevenLabs music | Generated by the team with ElevenLabs |";
    const music = creditLines({ file: "CREDITS.md", text: [...head, terms, ours].join("\n") });
    expect(findCredit("public/audio/music/fight.mp3", music)?.licence).toEqual({
      status: "not-allowed",
      label: "ElevenLabs Terms of Service",
    });
    expect(findCredit("public/audio/music/win.mp3", music)?.licence).toEqual({
      status: "ok",
      label: "Generated by the team with ElevenLabs",
    });
  });

  it("does not take a lower-case by, such as used by the fight, for a CC BY author", () => {
    const head = ["| Asset | Used for | URL | Licence |", "|---|---|---|---|"];
    const row = "| Cyclops Rig | `public/models/cyclops.glb`, used by the Polyphemus fight | https://x | CC BY 4.0 |";
    const rig = buildReport([file("public/models/cyclops.glb")], [{ file: "CREDITS.md", text: [...head, row].join("\n") }]);
    expect(rig.rows[0]?.gap).toBe("CC BY without an author");
    expect(readLicence("Ogre by sam_pie, CC BY 4.0").status).toBe("no-author");
    expect(readLicence("Ogre by @sam_pie, CC BY 4.0").label).toBe("CC BY 4.0, by @sam_pie");
    expect(readLicence("Ogre by 3dSam, CC BY 4.0").status).toBe("ok");
  });

  it("does not read a line that denies CC0 as CC0", () => {
    const denied = "`public/models/x.glb` is not CC0, licence unknown.";
    expect(readLicence(denied).status).toBe("missing");
    expect(readLicence("a non-CC0 file").status).toBe("missing");
    const report = buildReport([file("public/models/x.glb")], [{ file: "CREDITS.md", text: denied }]);
    expect(report.rows[0]?.gap).toBe("no licence on the credit line");
  });

  it("refuses the Creative Commons variants the rules do not allow", () => {
    expect(readLicence("CC BY-NC 4.0")).toEqual({ status: "not-allowed", label: "CC BY-NC 4.0" });
    expect(readLicence("CC BY-SA 3.0").status).toBe("not-allowed");
    expect(readLicence("CC BY-NC-ND").status).toBe("not-allowed");
    expect(readLicence("royalty-free").status).toBe("not-allowed");
  });

  it("refuses those variants when they are written with a Unicode hyphen or dash", () => {
    // A non-breaking hyphen (U+2011) and an en dash (U+2013), as copied from a web page.
    expect(readLicence("CC BY\u2011NC 4.0", "X by Sam | CC BY\u2011NC 4.0").status).toBe("not-allowed");
    expect(readLicence("CC BY\u2013SA").status).toBe("not-allowed");
    expect(readLicence("CC\u2011BY\u00A04.0", "X by Sam").label).toBe("CC BY 4.0, by Sam");
    expect(readLicence("CC\u20110").label).toBe("CC0");
  });

  it("says missing when the text names no licence", () => {
    expect(readLicence("the hero, 700 KB")).toEqual({ status: "missing", label: "" });
  });
});

describe("the paths a line names", () => {
  it("finds paths, patterns and folders anywhere under public/", () => {
    expect(pathsNamed("`public/hdri/cave.hdr`, and public/textures/rock_* plus `public/audio/sfx/`.")).toEqual([
      "public/hdri/cave.hdr",
      "public/textures/rock_*",
      "public/audio/sfx/",
    ]);
    expect(pathsNamed("`public/favicon.svg`, `public/ui/owl.svg` and `public/draco/`")).toEqual([
      "public/favicon.svg",
      "public/ui/owl.svg",
      "public/draco/",
    ]);
  });

  it("drops a full stop after a path and ignores paths outside public/", () => {
    expect(pathsNamed("See public/models/hero.glb. Not src/public/models/x.glb or docs/models/x.md.")).toEqual([
      "public/models/hero.glb",
    ]);
    // The word public/ alone names nothing, so one line cannot credit everything.
    expect(pathsNamed("Everything under public/ is ours.")).toEqual([]);
  });

  it("drops the stars of markdown bold, so a bold path is not read as a pattern", () => {
    expect(pathsNamed("**public/hdri/sky.hdr** and *public/models/a.glb* and **public/audio/sfx/**")).toEqual([
      "public/hdri/sky.hdr",
      "public/models/a.glb",
      "public/audio/sfx/",
    ]);
    expect(pathsNamed("public/textures/rock_* and public/models/*.glb")).toEqual([
      "public/textures/rock_*",
      "public/models/*.glb",
    ]);
  });

  it("does not read a path with a leading slash, a ../ or a bracket in the name", () => {
    expect(pathsNamed("/public/models/x.glb and ../public/models/y.glb")).toEqual([]);
    expect(pathsNamed("`public/models/Sword (1).glb`")).toEqual(["public/models/Sword"]);
  });
});

describe("matching a pattern to a file", () => {
  it("matches the exact path, a star inside one folder, and a folder with a trailing slash", () => {
    expect(matchKind("public/models/a.glb", "public/models/a.glb")).toBe("exact");
    expect(matchKind("public/textures/rock_*", "public/textures/rock_diff_1k.jpg")).toBe("glob");
    expect(matchKind("public/audio/sfx/", "public/audio/sfx/won.mp3")).toBe("folder");
  });

  it("does not let a star cross a folder or a dot stand for any letter", () => {
    expect(matchKind("public/audio/*", "public/audio/sfx/won.mp3")).toBeNull();
    expect(matchKind("public/models/a.glb", "public/models/aXglb")).toBeNull();
    expect(matchKind("public/models/*.glb", "public/models/aXglb")).toBeNull();
    expect(matchKind("public/audio/sfx", "public/audio/sfx/won.mp3")).toBeNull();
  });
});

describe("finding the credit for a file", () => {
  it("takes the licence from the Licence column of a table row", () => {
    const credit = findCredit("public/hdri/cave.hdr", lines);
    expect(credit).toMatchObject({ file: "CREDITS.md", line: 5, licence: { status: "ok", label: "CC0" } });
  });

  it("credits every file a star pattern covers", () => {
    expect(findCredit("public/textures/rock_diff.jpg", lines)?.line).toBe(6);
    expect(findCredit("public/textures/sand_diff.jpg", lines)).toBeNull();
  });

  it("credits a folder in CREDITS.md, but not a folder named in a model log", () => {
    expect(findCredit("public/audio/sfx/won.mp3", lines)?.licence.label).toBe("generated by the team with ElevenLabs");
    // The model log says "Files go under `public/models/` ... CC0": that is not a credit for every model.
    expect(findCredit("public/models/unknown.glb", lines)).toBeNull();
  });

  it("prefers the line that carries a licence when two lines name the file", () => {
    const credit = findCredit("public/models/hero.glb", lines);
    expect(credit).toMatchObject({ file: "docs/models/hero.md", line: 6, licence: { label: "CC0" } });
  });

  it("lets an exact line with a licence that is not allowed beat a folder credit", () => {
    expect(findCredit("public/audio/sfx/horn.mp3", lines)?.licence).toEqual({
      status: "not-allowed",
      label: "CC BY-SA 3.0",
    });
  });

  const FOLDER = "Everything under `public/audio/sfx/` was generated by the team with ElevenLabs.";
  const credit = (path: string, ...text: string[]) =>
    findCredit(path, creditLines({ file: "CREDITS.md", text: text.join("\n") }));

  it("lets a pattern with a licence that is not allowed beat a folder credit", () => {
    const banned = "`public/audio/sfx/horn_*` are CC BY-NC 4.0";
    expect(credit("public/audio/sfx/horn_1.mp3", FOLDER, banned)?.licence.status).toBe("not-allowed");
    expect(credit("public/audio/sfx/horn_1.mp3", banned, FOLDER)?.licence.status).toBe("not-allowed");
    expect(credit("public/audio/sfx/won.mp3", FOLDER, banned)?.licence.status).toBe("ok");
  });

  it("lets an exact CC BY row with no author beat a folder credit", () => {
    const head = ["| Clip | File | Licence |", "|---|---|---|"];
    const row = "| Horn | `public/audio/sfx/horn.mp3` | CC BY 4.0 |";
    expect(credit("public/audio/sfx/horn.mp3", FOLDER, "", ...head, row)?.licence).toEqual({
      status: "no-author",
      label: "CC BY 4.0",
    });
  });

  it("keeps an exact allowed credit ahead of a folder that is not allowed", () => {
    const folder = "Everything under `public/audio/sfx/` is CC BY-NC 4.0.";
    const exact = "`public/audio/sfx/won.mp3` was made by the team.";
    expect(credit("public/audio/sfx/won.mp3", folder, exact)?.licence.status).toBe("ok");
    expect(credit("public/audio/sfx/lost.mp3", folder, exact)?.licence.status).toBe("not-allowed");
  });

  it("never lets a line with no licence beat one that states a licence", () => {
    const bare = "- File: `public/audio/sfx/won.mp3`, 49 KB.";
    expect(credit("public/audio/sfx/won.mp3", bare, FOLDER)?.licence.status).toBe("ok");
  });
});

describe("the report", () => {
  const report = buildReport(
    [
      file("public/models/warrior.glb", 744_000),
      file("public/hdri/cave.hdr", 1_800_000),
      file("public/models/ogre.glb"),
      file("public/models/hydra.glb"),
      file("public/models/serpent.glb"),
      file("public/models/club.glb"),
      file("public/models/stake.glb"),
      file("public/models/hero.glb"),
      file("public/models/nobody.glb"),
      file("public/audio/sfx/won.mp3", 500),
      file("public/audio/sfx/index.json", 20),
      file("public/audio/.gitkeep", 0),
      file("public/audio/music/theme.mp3"),
    ],
    sources,
  );
  const row = (path: string) => report.rows.find((r) => r.path === path);

  it("sorts the rows by path and counts files, bytes, assets and gaps", () => {
    expect(report.rows[0]?.path).toBe("public/audio/.gitkeep");
    expect(report.files).toBe(13);
    expect(report.bytes).toBe(744_000 + 1_800_000 + 8 * 1000 + 500 + 20);
    expect(report.assets).toBe(11);
    expect(report.credited).toBe(4);
    expect(report.gaps).toBe(7);
  });

  it("gives each gap its kind", () => {
    expect(row("public/models/nobody.glb")?.gap).toBe("no credit");
    expect(row("public/audio/music/theme.mp3")?.gap).toBe("no credit");
    expect(row("public/models/warrior.glb")).toMatchObject({
      gap: "no licence on the credit line",
      where: "docs/models/hero.md:7",
    });
    expect(row("public/models/stake.glb")?.gap).toBe("no licence on the credit line");
    expect(row("public/models/hydra.glb")?.gap).toBe("CC BY without an author");
    expect(row("public/models/serpent.glb")).toMatchObject({ gap: "licence not allowed", licence: "CC BY-NC 4.0" });
    expect(row("public/models/club.glb")).toMatchObject({ gap: "licence not allowed", licence: "MIT" });
  });

  it("lists credited files with the licence and the line that credits them", () => {
    expect(row("public/hdri/cave.hdr")).toMatchObject({ gap: null, licence: "CC0", where: "CREDITS.md:5" });
    expect(row("public/models/ogre.glb")).toMatchObject({ gap: null, licence: "CC BY 4.0, by Sam Pie" });
    expect(row("public/audio/sfx/won.mp3")).toMatchObject({ gap: null, where: "CREDITS.md:15" });
  });

  it("notes a model that is credited in a model log but not in CREDITS.md", () => {
    expect(row("public/models/hero.glb")).toMatchObject({ gap: null, where: "docs/models/hero.md:6" });
    expect(row("public/models/hero.glb")?.note).toContain("not in CREDITS.md");
    expect(row("public/hdri/cave.hdr")?.note).toBe("");
  });

  it("never counts bookkeeping files as assets or gaps, and says which rule decided", () => {
    expect(row("public/audio/sfx/index.json")).toMatchObject({ asset: false, gap: null });
    expect(row("public/audio/sfx/index.json")?.licence).toContain("not an asset (index.json");
    expect(row("public/audio/.gitkeep")?.licence).toBe("not an asset (dot file)");
    expect(bookkeepingRule("public/models/pack/License.txt")).toBe("text file");
    expect(bookkeepingRule("public/models/pack/scene.gltf")).toBeNull();
    expect(bookkeepingRule("public/models/pack/data.json")).toBeNull();
  });

  it("groups the gaps in the summary by who fixes them", () => {
    const summary = summaryLines(report);
    expect(summary[0]).toBe("13 files, 2.6 MB (2552520 bytes). 11 assets: 4 credited, 7 gaps. 2 not assets.");
    expect(summary).toContain("GAP, audio (luvudeshi's agent), no credit: public/audio/music/{theme.mp3}");
    expect(summary).toContain(
      "GAP, models, textures and skies (the lead's agents), licence not allowed: public/models/{club.glb, serpent.glb}",
    );
    expect(gapOwner("public/textures/rock.jpg")).toContain("the lead's agents");
  });

  it("counts the files of a folder instead of naming them when there are many", () => {
    const many = buildReport(
      Array.from({ length: 7 }, (_, i) => file(`public/audio/taunts/t${String(i)}.mp3`)),
      sources,
    );
    expect(summaryLines(many)).toContain("GAP, audio (luvudeshi's agent), no credit: public/audio/taunts/ (7 files)");
  });

  it("prints one line per file as text and as a markdown table", () => {
    const text = formatText(report).split("\n");
    expect(text[0]).toMatch(/^File\s+Size\s+Licence\s+Credited at$/);
    expect(text.filter((line) => line.startsWith("public/"))).toHaveLength(13);
    expect(text.find((line) => line.startsWith("public/hdri/cave.hdr"))).toMatch(
      /^public\/hdri\/cave\.hdr {2,}1\.8 MB {2,}CC0 {2,}CREDITS\.md:5$/,
    );
    // Columns line up: the size starts at the same place on every row.
    const sizeAt = text[0]?.indexOf("Size") ?? -1;
    const nobody = text.find((line) => line.startsWith("public/models/nobody.glb"));
    expect(nobody?.slice(sizeAt)).toMatch(/^1 KB {2,}GAP: no credit/);

    const markdown = formatMarkdown(report).split("\n");
    expect(markdown).toContain("| File | Size | Licence | Credited at |");
    expect(markdown).toContain("| `public/models/nobody.glb` | 1 KB | GAP: no credit | - |");
    expect(markdown.filter((line) => line.startsWith("| `public/"))).toHaveLength(13);
  });

  it("has no gaps when every asset is credited", () => {
    const clean = buildReport([file("public/hdri/cave.hdr"), file("public/audio/sfx/index.json")], sources);
    expect(clean.gaps).toBe(0);
    expect(summaryLines(clean)).toHaveLength(1);
    const one = buildReport([file("public/hdri/cave.hdr"), file("public/models/nobody.glb")], sources);
    expect(summaryLines(one)[0]).toContain("1 credited, 1 gap. 0 not assets.");
  });
});

describe("bundled software and model files", () => {
  const HEAD = ["| Software | Files | Source | Licence |", "|---|---|---|---|"];
  const DECODER = "| Mesh decoder by Example Corp | `public/draco/` | https://example.com/decoder | Apache-2.0 |";
  const report = (paths: string[], ...rows: string[]) =>
    buildReport(paths.map((path) => file(path)), [{ file: "CREDITS.md", text: [...HEAD, ...rows].join("\n") }]);

  it("puts a file in the software class by its folder, never by its name or its credit", () => {
    expect(assetClass("public/draco/draco_decoder.wasm")).toBe("software");
    expect(assetClass("public/mediapipe/wasm/vision.js")).toBe("software");
    expect(assetClass("public/models/decoder.wasm")).toBe("art");
    expect(assetClass("public/dracoish/decoder.js")).toBe("art");
    expect(assetClass("public/favicon.svg")).toBe("art");
  });

  it("reads Apache-2.0, MIT and BSD with 2 or 3 clauses, in the ways they are usually written", () => {
    const line = (licence: string) => `Decoder by Example Corp, https://example.com/decoder, ${licence}`;
    expect(readSoftwareLicence(line("Apache-2.0"))).toEqual({ status: "ok", label: "Apache-2.0, by Example Corp" });
    expect(readSoftwareLicence(line("Apache 2.0")).label).toBe("Apache-2.0, by Example Corp");
    expect(readSoftwareLicence(line("Apache License 2.0")).status).toBe("ok");
    expect(readSoftwareLicence(line("Apache License, Version 2.0")).status).toBe("ok");
    expect(readSoftwareLicence(line("MIT")).label).toBe("MIT, by Example Corp");
    expect(readSoftwareLicence(line("BSD 3-Clause")).label).toBe("BSD-3-Clause, by Example Corp");
    expect(readSoftwareLicence(line("BSD-2-Clause")).label).toBe("BSD-2-Clause, by Example Corp");
  });

  it("does not read a licence it does not know", () => {
    const line = (licence: string) => `Decoder by Example Corp, https://example.com/decoder, ${licence}`;
    expect(readSoftwareLicence(line("BSD")).status).toBe("missing");
    expect(readSoftwareLicence(line("BSD 4-Clause")).status).toBe("missing");
    expect(readSoftwareLicence(line("Apache 1.1")).status).toBe("missing");
    expect(readSoftwareLicence(line("GPL-3.0")).status).toBe("missing");
    expect(readSoftwareLicence(line("mit")).status).toBe("missing");
  });

  it("needs the author and a link to the source on the same line", () => {
    expect(readSoftwareLicence("Decoder, https://example.com/decoder, MIT")).toEqual({ status: "no-author", label: "MIT" });
    expect(readSoftwareLicence("Decoder by Example Corp, MIT")).toEqual({ status: "no-source", label: "MIT" });
    expect(readSoftwareLicence("MIT", "| Decoder by Example Corp | https://example.com | MIT |").status).toBe("ok");
  });

  it("does not let an art licence or our own work stand in for a software licence", () => {
    expect(readSoftwareLicence("Decoder by Example Corp, https://example.com, CC0")).toEqual({
      status: "not-allowed",
      label: "CC0",
    });
    expect(readSoftwareLicence("made by the team, https://example.com").status).toBe("not-allowed");
    expect(readSoftwareLicence("Decoder by Sam Pie, https://example.com, CC BY 4.0").status).toBe("not-allowed");
    expect(readSoftwareLicence("Decoder by Example Corp, https://example.com, MIT, non-commercial").status).toBe("not-allowed");
  });

  it("credits a software folder from CREDITS.md and says so on each row", () => {
    const built = report(["public/draco/decoder.js", "public/draco/decoder.wasm", "public/hdri/cave.hdr"], DECODER);
    const decoder = built.rows.find((row) => row.path === "public/draco/decoder.wasm");
    expect(decoder).toMatchObject({
      gap: null,
      kind: "software",
      licence: "Bundled software: Apache-2.0, by Example Corp",
      where: "CREDITS.md:3",
    });
    expect(built.software).toBe(2);
    expect(built.gaps).toBe(1);
    expect(summaryLines(built)[1]).toBe(
      "Art and sound: 1. Bundled software and model files under their own open licence: 2.",
    );
  });

  it("still refuses a software licence on art and sound, in a table and in a sentence", () => {
    const club = "| Club by Example Corp | `public/models/club.glb` | https://example.com/club | Apache-2.0 |";
    const built = report(["public/models/club.glb"], club);
    expect(built.rows.find((row) => row.path === "public/models/club.glb")).toMatchObject({
      gap: "licence not allowed",
      kind: "art",
      licence: "Apache-2.0",
    });
    const sentence = "`public/ui/icon.svg` and `public/audio/sfx/hit.mp3` by Sam Pie, https://example.com, MIT.";
    const loose = buildReport(
      [file("public/ui/icon.svg"), file("public/audio/sfx/hit.mp3")],
      [{ file: "CREDITS.md", text: sentence }],
    );
    expect(loose.rows.map((row) => row.gap)).toEqual(["no licence on the credit line", "no licence on the credit line"]);
    expect(loose.software).toBe(0);
  });

  it("gives each software gap its kind", () => {
    const built = report(
      ["public/draco/a.js", "public/draco/b.js", "public/draco/c.js", "public/draco/d.js", "public/mediapipe/pose.task"],
      "| Wrapper | `public/draco/a.js` | https://example.com/a | MIT |",
      "| Wrapper by Example Corp | `public/draco/b.js` | in the package | MIT |",
      "| Wrapper by Example Corp | `public/draco/c.js` | https://example.com/c | CC0 |",
      "| Wrapper by Example Corp | `public/draco/d.js` | https://example.com/d | Example Corp terms of use |",
    );
    expect(built.rows.map((row) => row.gap)).toEqual([
      "software licence without an author",
      "software credit without a source link",
      "licence not allowed",
      "licence not allowed",
      "no credit",
    ]);
    expect(built.credited).toBe(0);
    expect(summaryLines(built)).toContain(
      "GAP, bundled software and model files (the lead's agents), no credit: public/mediapipe/{pose.task}",
    );
  });

  it("lets an exact software line that is not allowed beat a folder credit", () => {
    const banned = "| Plugin by Example Corp | `public/draco/plugin.js` | https://example.com/p | Example Corp terms of use |";
    const built = report(["public/draco/decoder.js", "public/draco/plugin.js"], DECODER, banned);
    expect(built.rows.map((row) => row.gap)).toEqual([null, "licence not allowed"]);
  });

  it("does not take a model log's folder line as a credit for software", () => {
    const log = "The decoder in `public/draco/` is by Example Corp, https://example.com/decoder, Apache-2.0.";
    const built = buildReport([file("public/draco/decoder.js")], [{ file: "docs/models.md", text: log }]);
    expect(built.rows[0]?.gap).toBe("no credit");
  });

  it("checks icons and other files outside the old asset folders as art", () => {
    const owl = "| Owl | `public/ui/owl.svg` | Drawn in code | Drawn by the team |";
    const built = report(["public/favicon.svg", "public/ui/owl.svg"], owl);
    expect(built.rows.map((row) => row.gap)).toEqual(["no credit", null]);
    expect(built.rows[1]?.licence).toBe("Drawn by the team");
    expect(gapOwner("public/favicon.svg")).toBe("icons and screen art (the lead's agents)");
    expect(gapOwner("public/draco/decoder.js")).toBe("bundled software and model files (the lead's agents)");
    expect(gapOwner("public/models/a.glb")).toBe("models, textures and skies (the lead's agents)");
  });

  it("says which expected folder has no files on this machine", () => {
    const expected = ["public/draco/", "public/mediapipe/"];
    const built = buildReport([file("public/draco/decoder.js")], [{ file: "CREDITS.md", text: [...HEAD, DECODER].join("\n") }], expected);
    expect(built.absent).toEqual(["public/mediapipe/"]);
    expect(built.gaps).toBe(0);
    const notes = summaryLines(built).filter((line) => line.startsWith("NOTE, "));
    expect(notes).toHaveLength(1);
    expect(notes[0]).toMatch(/^NOTE, public\/mediapipe\/: no files on this machine/);
    expect(buildReport([file("public/draco/decoder.js")], []).absent).toEqual([]);
  });
});

