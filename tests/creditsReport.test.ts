import { describe, expect, it } from "vitest";
import {
  bookkeepingRule,
  buildReport,
  creditLines,
  findCredit,
  formatMarkdown,
  formatText,
  gapOwner,
  matchKind,
  pathsNamed,
  readLicence,
  sizeText,
  summaryLines,
} from "../scripts/credits-report.mjs";

// Everything here is made-up credit text and file lists. The real report is run with `make credits`.

const CREDITS = [
  "# Credits",
  "",
  "| Asset | Used for | URL | Licence |",
  "|---|---|---|---|",
  "| Small Cave | Light, `public/hdri/cave.hdr` | https://example.com/cave | CC0 |",
  "| Rock | Walls, `public/textures/rock_*` | https://example.com/rock | CC0 |",
  "| Ogre by Sam Pie | `public/models/ogre.glb` | https://example.com/ogre | CC BY 4.0 |",
  "| Hydra | `public/models/hydra.glb` | https://example.com/hydra | CC BY 4.0 |",
  "| Serpent | `public/models/serpent.glb` | https://example.com/serpent | CC BY-NC 4.0 |",
  "| Club | `public/models/club.glb` | https://example.com/club | MIT |",
  "| Stake | `public/models/stake.glb` | https://example.com/stake | |",
  "",
  "## Audio",
  "",
  "Everything under `public/audio/sfx/` was generated by the team with ElevenLabs.",
  "The clip `public/audio/sfx/horn.mp3` is CC BY-SA 3.0.",
].join("\n");

const MODEL_LOG = [
  "Files go under `public/models/` (never a CDN). Only CC0 or CC-BY files.",
  "| Field | Value |",
  "|---|---|",
  "| File | `public/models/hero.glb`, 700 KB |",
  "",
  "CREDITS line: `| Mannequin (Quaternius) | public/models/hero.glb, the hero | https://example.com | CC0 |`",
  "- File: `public/models/warrior.glb`, 744 KB.",
].join("\n");

const sources = [
  { file: "CREDITS.md", text: CREDITS },
  { file: "docs/models/hero.md", text: MODEL_LOG },
];
const lines = sources.flatMap(creditLines);

function file(path: string, size = 1000) {
  return { path, size };
}

describe("reading a licence", () => {
  it("reads CC0, with or without a version", () => {
    expect(readLicence("CC0")).toEqual({ status: "ok", label: "CC0" });
    expect(readLicence("CC0 1.0 (License.txt in both packs)").label).toBe("CC0");
  });

  it("reads CC BY only when the line names an author with the word by", () => {
    expect(readLicence('"Ogre" (https://example.com) by Sam Pie is licensed under CC BY 4.0')).toEqual({
      status: "ok",
      label: "CC BY 4.0, by Sam Pie",
    });
    expect(readLicence("Ogre, CC BY 4.0")).toEqual({ status: "no-author", label: "CC BY 4.0" });
    expect(readLicence("CC-BY", "Ogre by Sam Pie | CC-BY").label).toBe("CC BY, by Sam Pie");
  });

  it("reads work made by the team", () => {
    expect(readLicence("was generated by the team with ElevenLabs.")).toEqual({
      status: "ok",
      label: "generated by the team with ElevenLabs",
    });
    expect(readLicence("made by the team").status).toBe("ok");
  });

  it("reads the ElevenLabs terms, the form our music rows use, as made by the team", () => {
    expect(readLicence("ElevenLabs Terms of Service and Music Terms, see below")).toEqual({
      status: "ok",
      label: "made by the team with ElevenLabs (its Terms of Service)",
    });
    const row = "| Battle music | `public/audio/music/fight.mp3` | ElevenLabs music | ElevenLabs Terms of Service |";
    const table = ["| Clip | File | Source | Licence |", "|---|---|---|---|", row].join("\n");
    const credit = findCredit("public/audio/music/fight.mp3", creditLines({ file: "CREDITS.md", text: table }));
    expect(credit).toMatchObject({ line: 3, licence: { status: "ok" } });
  });

  it("refuses the Creative Commons variants the rules do not allow", () => {
    expect(readLicence("CC BY-NC 4.0")).toEqual({ status: "not-allowed", label: "CC BY-NC 4.0" });
    expect(readLicence("CC BY-SA 3.0").status).toBe("not-allowed");
    expect(readLicence("CC BY-NC-ND").status).toBe("not-allowed");
    expect(readLicence("royalty-free").status).toBe("not-allowed");
  });

  it("says missing when the text names no licence", () => {
    expect(readLicence("the hero, 700 KB")).toEqual({ status: "missing", label: "" });
  });
});

describe("the paths a line names", () => {
  it("finds paths, patterns and folders under the four asset folders", () => {
    expect(pathsNamed("`public/hdri/cave.hdr`, and public/textures/rock_* plus `public/audio/sfx/`.")).toEqual([
      "public/hdri/cave.hdr",
      "public/textures/rock_*",
      "public/audio/sfx/",
    ]);
  });

  it("drops a full stop after a path and ignores other folders", () => {
    expect(pathsNamed("See public/models/hero.glb. Not public/draco/ or src/public/models/x.glb.")).toEqual([
      "public/models/hero.glb",
    ]);
  });
});

describe("matching a pattern to a file", () => {
  it("matches the exact path, a star inside one folder, and a folder with a trailing slash", () => {
    expect(matchKind("public/models/a.glb", "public/models/a.glb")).toBe("exact");
    expect(matchKind("public/textures/rock_*", "public/textures/rock_diff_1k.jpg")).toBe("glob");
    expect(matchKind("public/audio/sfx/", "public/audio/sfx/won.mp3")).toBe("folder");
  });

  it("does not let a star cross a folder or a dot stand for any letter", () => {
    expect(matchKind("public/audio/*", "public/audio/sfx/won.mp3")).toBeNull();
    expect(matchKind("public/models/a.glb", "public/models/aXglb")).toBeNull();
    expect(matchKind("public/models/*.glb", "public/models/aXglb")).toBeNull();
    expect(matchKind("public/audio/sfx", "public/audio/sfx/won.mp3")).toBeNull();
  });
});

describe("finding the credit for a file", () => {
  it("takes the licence from the Licence column of a table row", () => {
    const credit = findCredit("public/hdri/cave.hdr", lines);
    expect(credit).toMatchObject({ file: "CREDITS.md", line: 5, licence: { status: "ok", label: "CC0" } });
  });

  it("credits every file a star pattern covers", () => {
    expect(findCredit("public/textures/rock_diff.jpg", lines)?.line).toBe(6);
    expect(findCredit("public/textures/sand_diff.jpg", lines)).toBeNull();
  });

  it("credits a folder in CREDITS.md, but not a folder named in a model log", () => {
    expect(findCredit("public/audio/sfx/won.mp3", lines)?.licence.label).toBe("generated by the team with ElevenLabs");
    // The model log says "Files go under `public/models/` ... CC0": that is not a credit for every model.
    expect(findCredit("public/models/unknown.glb", lines)).toBeNull();
  });

  it("prefers the line that carries a licence when two lines name the file", () => {
    const credit = findCredit("public/models/hero.glb", lines);
    expect(credit).toMatchObject({ file: "docs/models/hero.md", line: 6, licence: { label: "CC0" } });
  });

  it("lets an exact line with a licence that is not allowed beat a folder credit", () => {
    expect(findCredit("public/audio/sfx/horn.mp3", lines)?.licence).toEqual({
      status: "not-allowed",
      label: "CC BY-SA 3.0",
    });
  });
});

describe("the report", () => {
  const report = buildReport(
    [
      file("public/models/warrior.glb", 744_000),
      file("public/hdri/cave.hdr", 1_800_000),
      file("public/models/ogre.glb"),
      file("public/models/hydra.glb"),
      file("public/models/serpent.glb"),
      file("public/models/club.glb"),
      file("public/models/stake.glb"),
      file("public/models/hero.glb"),
      file("public/models/nobody.glb"),
      file("public/audio/sfx/won.mp3", 500),
      file("public/audio/sfx/index.json", 20),
      file("public/audio/.gitkeep", 0),
      file("public/audio/music/theme.mp3"),
    ],
    sources,
  );
  const row = (path: string) => report.rows.find((r) => r.path === path);

  it("sorts the rows by path and counts files, bytes, assets and gaps", () => {
    expect(report.rows[0]?.path).toBe("public/audio/.gitkeep");
    expect(report.files).toBe(13);
    expect(report.bytes).toBe(744_000 + 1_800_000 + 8 * 1000 + 500 + 20);
    expect(report.assets).toBe(11);
    expect(report.credited).toBe(4);
    expect(report.gaps).toBe(7);
  });

  it("gives each gap its kind", () => {
    expect(row("public/models/nobody.glb")?.gap).toBe("no credit");
    expect(row("public/audio/music/theme.mp3")?.gap).toBe("no credit");
    expect(row("public/models/warrior.glb")).toMatchObject({
      gap: "no licence on the credit line",
      where: "docs/models/hero.md:7",
    });
    expect(row("public/models/stake.glb")?.gap).toBe("no licence on the credit line");
    expect(row("public/models/hydra.glb")?.gap).toBe("CC BY without an author");
    expect(row("public/models/serpent.glb")).toMatchObject({ gap: "licence not allowed", licence: "CC BY-NC 4.0" });
    expect(row("public/models/club.glb")).toMatchObject({ gap: "licence not allowed", licence: "MIT" });
  });

  it("lists credited files with the licence and the line that credits them", () => {
    expect(row("public/hdri/cave.hdr")).toMatchObject({ gap: null, licence: "CC0", where: "CREDITS.md:5" });
    expect(row("public/models/ogre.glb")).toMatchObject({ gap: null, licence: "CC BY 4.0, by Sam Pie" });
    expect(row("public/audio/sfx/won.mp3")).toMatchObject({ gap: null, where: "CREDITS.md:15" });
  });

  it("notes a model that is credited in a model log but not in CREDITS.md", () => {
    expect(row("public/models/hero.glb")).toMatchObject({ gap: null, where: "docs/models/hero.md:6" });
    expect(row("public/models/hero.glb")?.note).toContain("not in CREDITS.md");
    expect(row("public/hdri/cave.hdr")?.note).toBe("");
  });

  it("never counts bookkeeping files as assets or gaps, and says which rule decided", () => {
    expect(row("public/audio/sfx/index.json")).toMatchObject({ asset: false, gap: null });
    expect(row("public/audio/sfx/index.json")?.licence).toContain("not an asset (index.json");
    expect(row("public/audio/.gitkeep")?.licence).toBe("not an asset (dot file)");
    expect(bookkeepingRule("public/models/pack/License.txt")).toBe("text file");
    expect(bookkeepingRule("public/models/pack/scene.gltf")).toBeNull();
    expect(bookkeepingRule("public/models/pack/data.json")).toBeNull();
  });

  it("groups the gaps in the summary by who fixes them", () => {
    const summary = summaryLines(report);
    expect(summary[0]).toBe("13 files, 2.6 MB (2552520 bytes). 11 assets: 4 credited, 7 gaps. 2 not assets.");
    expect(summary).toContain("GAP, audio (luvudeshi's agent), no credit: public/audio/music/{theme.mp3}");
    expect(summary).toContain(
      "GAP, models, textures and skies (the lead's agents), licence not allowed: public/models/{club.glb, serpent.glb}",
    );
    expect(gapOwner("public/textures/rock.jpg")).toContain("the lead's agents");
  });

  it("counts the files of a folder instead of naming them when there are many", () => {
    const many = buildReport(
      Array.from({ length: 7 }, (_, i) => file(`public/audio/taunts/t${String(i)}.mp3`)),
      sources,
    );
    expect(summaryLines(many)).toContain("GAP, audio (luvudeshi's agent), no credit: public/audio/taunts/ (7 files)");
  });

  it("prints one line per file as text and as a markdown table", () => {
    const text = formatText(report).split("\n");
    expect(text[0]).toMatch(/^File\s+Size\s+Licence\s+Credited at$/);
    expect(text.filter((line) => line.startsWith("public/"))).toHaveLength(13);
    expect(text.find((line) => line.startsWith("public/hdri/cave.hdr"))).toMatch(
      /^public\/hdri\/cave\.hdr {2,}1\.8 MB {2,}CC0 {2,}CREDITS\.md:5$/,
    );
    // Columns line up: the size starts at the same place on every row.
    const sizeAt = text[0]?.indexOf("Size") ?? -1;
    const nobody = text.find((line) => line.startsWith("public/models/nobody.glb"));
    expect(nobody?.slice(sizeAt)).toMatch(/^1 KB {2,}GAP: no credit/);

    const markdown = formatMarkdown(report).split("\n");
    expect(markdown).toContain("| File | Size | Licence | Credited at |");
    expect(markdown).toContain("| `public/models/nobody.glb` | 1 KB | GAP: no credit | - |");
    expect(markdown.filter((line) => line.startsWith("| `public/"))).toHaveLength(13);
  });

  it("has no gaps when every asset is credited", () => {
    const clean = buildReport([file("public/hdri/cave.hdr"), file("public/audio/sfx/index.json")], sources);
    expect(clean.gaps).toBe(0);
    expect(summaryLines(clean)).toHaveLength(1);
  });
});

describe("sizes", () => {
  it("uses units of 1000", () => {
    expect(sizeText(0)).toBe("0 B");
    expect(sizeText(999)).toBe("999 B");
    expect(sizeText(757_000)).toBe("757 KB");
    expect(sizeText(2_450_000)).toBe("2.5 MB");
  });
});
